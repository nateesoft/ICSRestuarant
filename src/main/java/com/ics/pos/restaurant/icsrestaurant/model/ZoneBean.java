package com.ics.pos.restaurant.icsrestaurant.model;


public class ZoneBean {

    private String compname;
    private String zonename;
    private Integer zoneindex;
    private String zonepicturepath;

    public String getCompname() {
        return compname;
    }

    public void setCompname(String compname) {
        this.compname = compname;
    }

    public String getZonename() {
        return zonename;
    }

    public void setZonename(String zonename) {
        this.zonename = zonename;
    }

    public Integer getZoneindex() {
        return zoneindex;
    }

    public void setZoneindex(Integer zoneindex) {
        this.zoneindex = zoneindex;
    }

    public String getZonepicturepath() {
        return zonepicturepath;
    }

    public void setZonepicturepath(String zonepicturepath) {
        this.zonepicturepath = zonepicturepath;
    }
    
    
}
